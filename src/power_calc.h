#pragma once
#include <stdint.h>
#include <string.h>

// ============================================================
//  power_calc.h — выбор режима энергосбережения и профили.
//
//  Без Arduino: собирается нативно и покрыто тестами.
//  Применение режима к железу — в power.cpp.
//
//  Два уровня. Эконом — режим по умолчанию: он ужимает то, что
//  не видно на глаз (реже опрос датчика, тусклее экран, радио
//  спит дольше между маячками), и ночью гасит экран по расписанию.
//  Обычный включается, когда с устройством работают, — то есть
//  на время секундомера.
//
//  Третьим был «выживание»: он выключал Wi-Fi на исходе заряда.
//  Убран намеренно. Экономил он около суток работы, но эти сутки
//  часы были глухими — ни дашборда, ни секундомера, ни свежего
//  времени, — и связь пропадала ровно тогда, когда на заряд и
//  хотелось посмотреть. Хуже того, выключенное радио уносило
//  единственный канал управления, и почти вся сложность этого
//  модуля состояла из подпорок под это одно свойство: срок
//  ручной фиксации, окно NTP раз в сутки, вето по заряду над
//  выбором пользователя, расхождение «выбрано / работает».
//
//  Работу, ради которой он был нужен, делают два рубежа, и оба
//  проще целого режима: панель гасится совсем на
//  POWER_SCREEN_OFF_PCT (OLED — крупнейший потребитель, он же
//  источник просадки), а на BATTERY_CRITICAL_PCT вместо погоды
//  встаёт перечёркнутая батарея — заряжать пора, и это видно
//  с другого конца комнаты.
// ============================================================

enum PowerMode : uint8_t {
    POWER_NORMAL = 0,
    POWER_ECO    = 1,
};

struct PowerProfile {
    const char* name;
    uint32_t    sensorMs;        // период опроса BMP280 (батарея обновляется чаще)
    uint8_t     contrastPct;     // масштаб авто-яркости, % от штатной
    bool        led;             // мигок WS2812 на каждый опрос
    bool        screenWindow;    // гасить экран вне рабочего окна
    uint8_t     listenInterval;  // маячков между пробуждениями радио
    int8_t      txDbm;           // мощность передатчика
};

inline const PowerProfile& powerProfile(PowerMode m) {
    static const PowerProfile P[2] = {
        //  name       sensorMs  contrast  led    window  listen  tx
        { "normal",    60000UL,      100,  true,  false,      1,  20 },
        { "eco",      120000UL,       60,  false, true,       5,  11 },
    };
    return P[m > POWER_ECO ? POWER_NORMAL : m];
}

// Попадает ли час в окно [onHour, offHour). Окно через полночь поддержано,
// совпадающие границы означают «круглые сутки».
inline bool hourInWindow(int hour, int onHour, int offHour) {
    if (onHour == offHour) return true;
    if (onHour <  offHour) return hour >= onHour && hour < offHour;
    return hour >= onHour || hour < offHour;
}

// Рабочий уровень: выбор пользователя, поправленный секундомером.
//
// Замер запускают, чтобы на него смотреть, поэтому он поднимает уровень до
// обычного независимо от выбранного: зафиксированный эконом ночью держал бы
// экран погашенным (профиль normal ночного окна не знает), а ужатое радио
// задерживало бы команды из браузера. Пауза считается работой — замер не
// окончен, и ронять связь посреди него незачем.
//
// Сам выбор при этом не теряется: он остаётся в chosen и возвращается со
// сбросом замера.
//
// Заряд здесь больше не участвует, и это единственное правило, которое
// осталось от прежних трёх. Раньше он выбирал выживание, потом получил право
// вето над ручной фиксацией — чтобы выживание не становилось тупиком. Без
// выживания выбирать зарядом нечего: оба уровня держат радио живым, а разница
// между ними — яркость, период опроса и сон радио, то есть то, что на грани
// разряда уже ничего не решает. Заряд теперь трогает не режим, а два рубежа:
// экран и предупреждение.
inline PowerMode powerEffectiveMode(PowerMode chosen, bool stopwatchActive) {
    return stopwatchActive ? POWER_NORMAL : chosen;
}

// Можно ли держать экран включённым. В обычном режиме — всегда.
inline bool powerScreenAllowed(PowerMode m, int hour, int onHour, int offHour) {
    if (!powerProfile(m).screenWindow) return true;
    return hourInWindow(hour, onHour, offHour);
}

// Последний рубеж: когда заряда почти не осталось, панель гасится независимо
// от режима и расписания. Она — самый крупный потребитель, и её выключение
// и продлевает работу, и снимает просадку напряжения, из-за которой
// устройство ушло бы в brownout раньше времени.
//
// Вынесено отдельно от расписания намеренно: расписание требует знать час, а
// этот рубеж — нет. Пока оба жили в одной функции, вызывающая сторона не могла
// проверить заряд, не имея времени, и без синхронизации NTP гашение по заряду
// не работало вовсе.
inline bool powerScreenBatteryOk(uint8_t pct, bool valid, uint8_t offPct) {
    return !(valid && pct <= offPct);
}

// Оба условия сразу — для случая, когда час известен.
inline bool powerScreenAllowedAt(PowerMode m, int hour, int onHour, int offHour,
                                 uint8_t pct, bool valid, uint8_t offPct) {
    if (!powerScreenBatteryOk(pct, valid, offPct)) return false;
    return powerScreenAllowed(m, hour, onHour, offHour);
}

// Разбор имени режима для API: "normal" | "eco".
inline bool powerModeFromName(const char* s, PowerMode* out) {
    if (!s || !out) return false;
    for (uint8_t m = POWER_NORMAL; m <= POWER_ECO; m++) {
        if (strcmp(s, powerProfile((PowerMode)m).name) == 0) {
            *out = (PowerMode)m;
            return true;
        }
    }
    return false;
}
