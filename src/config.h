#define POWER_NIGHT_ON_HOUR   22
#define POWER_NIGHT_OFF_HOUR   6
//   Ночью экран всё же можно зажечь из дашборда — но ненадолго: столько
//   он горит после команды, а дальше гаснет сам. Иначе забытый вечером
//   экран светил бы до утра, а это крупнейший потребитель.
#define POWER_SCREEN_PEEK_MS  30000UL
//   Заряда почти не осталось — гасим панель совсем, независимо от уровня,
//   расписания и подсветки: она самый крупный потребитель, и её отключение
//   заметно продлевает работу часов. Заодно снимает просадку, из-за которой
//   устройство уходило бы в brownout раньше времени. Этот рубеж не обходится
//   ничем: команда «включить экран» ниже него получает отказ, иначе полминуты
//   OLED роняли бы устройство совсем — вместо «показать время напоследок».
//
//   5 % — это ровно 3.70 В: ноль шкалы поднят до 3.65 ради ресурса банки
//   (battery_calc.h), и порог переехал вместе с ним, с прежних 3.60.
//
//   Сколько он даёт — измерено на ЛБП вместо банки, при 4.2 В: экран на
//   яркости около полной 160–180 мА, экран выключен 60–80 мА. То есть рубеж
//   снимает с банки около сотни миллиампер из ста семидесяти — и обвязку
//   панели (~40 мА: DC-DC на VCC, контроллер, развёртка), и сами пиксели
//   (до 60 мА). Прежняя формулировка «OLED тянет 150–180 мА против 20–30 у
//   радио» была неверна вдвойне: столько берёт всё устройство целиком, а
//   радио с чипом — это те самые 60–80 мА, которые остаются после гашения
//   и которых этот рубеж не касается вовсе.
//
#define POWER_SCREEN_OFF_PCT   5
//   Вернуть панель после гашения по заряду — только с запасом, по той же
//   причине, что и между сном и пробуждением ниже. Без него рубеж дребезжал:
//   погасшая панель снимала с банки до сотни миллиампер (замер выше),
//   напряжение отскакивало на десятки милливольт — внутреннее сопротивление,
//   полевики защиты, пружины холдера (README, «Просадка под нагрузкой»), — а
//   внизу кривой пункт шкалы стоит 5 мВ. Рубеж снова пропускал, панель
//   зажигалась, проседала и гасла опять, и так по кругу, пока банка не сядет
//   на величину отскока.
//
//   20 % — это ~3.76 В, почти на 60 мВ выше гашения: запас того же порядка,
//   что между сном и пробуждением (3.65 → 3.72 В). 10 % дали бы всего ~20 мВ —
//   меньше отскока, который тут ожидается. С BATTERY_CRITICAL_PCT порог
//   совпадает намеренно: панель возвращается тогда же, когда с циферблата
//   уходит знак разряда. Зарядке запас не мешает: ток TP4056 сразу поднимает
//   показание на десятки милливольт и больше, и с подключённым зарядом панель
//   загорается за секунды.
#define POWER_SCREEN_ON_PCT   20
//   Ноль шкалы — команда «стоп», а не просто ноль на индикаторе: на нём часы
//   уходят в deep sleep и тянут из банки на два порядка меньше: против
//   измеренных 60–80 мА с погашенным экраном (прежние «~25 мА» здесь были
//   втрое оптимистичнее правды).
//
//   Сколько именно — НЕ измерено, и «~20 мкА» из даташита — это один чип.
//   Во сне продолжают тянуть: делитель на GPIO2 (100к+100к — 18–21 мкА, уже
//   столько же, сколько весь чип), WS2812 в покое (0.5–1 мА по даташитам,
//   гашение цвета его не снимает, ключа по питанию нет) и модуль OLED в
//   sleep — его DC-DC и контроллер. Реалистично выходит около 1 мА. Тогда
//   ниже нуля шкалы банка всё-таки разряжается — до отсечки защиты примерно
//   за неделю, а не «никогда». Замерить ЛБП вместо банки, как замерено
//   остальное, и вписать сюда число. Без этого поднятый до 3.65 В ноль защищал
//   элемент лишь наполовину: разряд продолжался до brownout на 3.55 В, просто
//   медленнее. Время в RTC сон переживает, так что часы просыпаются с верным
//   временем и без похода в сеть.
#define POWER_SLEEP_PCT        0
//   Проснуться насовсем — только когда заряд поднялся с запасом. Запас
//   обязателен: во сне нагрузки нет, банка отдыхает и напряжение само
//   подрастает на десятки милливольт. Без него часы вставали бы на этом
//   отскоке, тут же садились обратно и загружались по кругу каждые пять минут.
//   10 % по кривой — это 3.72 В, выше любого отскока, то есть достижимо
