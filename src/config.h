// ── Батарея 18650 ────────────────────────────────────────────
//   BAT+ ──[100к]──●──[100к]── GND, точка ● → GPIO2 (ADC1).
#define BATTERY_ENABLED   true
#define BATTERY_ADC_PIN   2
#define BATTERY_DIVIDER   2.0f      // (R1+R2)/R2
//   Поправка АЦП+делителя: V_мультиметр / V_показанное. Измерена дважды на
//   разных уровнях заряда и в покое — 3.98/4.00 и 3.82/3.84, обе дали 0.995.
//   Совпадение до четвёртого знака означает систематическую ошибку, а не шум,
//   поэтому прежние 1.027 домножены на неё. Перемерять стоит на своей плате:
//   разброс 1 % резисторов делителя даёт свою поправку.
#define BATTERY_CAL       1.022f
//   Порог «разряжена»: жёлтый мигок LED и запись в журнал дашборда.
#define BATTERY_LOW_V     3.74f
//   Перечёркнутая батарея вместо температуры на экране. Задан в процентах, и
//   после подъёма нуля кривой до 3.65 В приходится примерно на 3.76 В.
#define BATTERY_CRITICAL_PCT  20
//   Ёмкость банки, для пересчёта процентов в мА·ч. Кулоновского счётчика в
//   схеме нет — единственный датчик это делитель на GPIO2, — поэтому мА·ч не
//   измеряются, а выводятся из напряжения через кривую.
//
//   Пока здесь стоит паспортная ёмкость элемента, и это верхняя граница:
//   в шкалу помещается не вся банка, а только окно 4.20…3.65 В — ниже нуля
//   шкалы заряд намеренно не выбирается (battery_calc.h). Сколько мА·ч в это
//   окно реально влезает, не измерено; выясняется одним прогоном до отсечки
//   с записью CSV, и тогда сюда встанет измеренное число.
#define BATTERY_USABLE_MAH    3300
//   Фильтр. Отсчёты набираются по одному из loop(), а не пачкой подряд:
//   пачка укладывается в миллисекунду и может целиком попасть в импульс
//   передачи Wi-Fi. Набор из 16 штук с шагом 25 мс растянут на ~0.4 с и
//   захватывает и провалы, и паузы, а медиана выбрасывает провалы.
#define BATTERY_SAMPLES        16
#define BATTERY_SAMPLE_GAP_MS  25UL
#define BATTERY_SMOOTH         0.10f   // вес свежего набора (меньше — плавнее)
#define BATTERY_JUMP_V         0.25f   // скачок больше — фильтр начать заново

// ── Энергосбережение ─────────────────────────────────────────
//   Два уровня, профили — в power_calc.h. Эконом стартовый: полная
//   мощность нужна, когда с часами работают, а не круглые сутки.
//   Обычный поднимается сам на время секундомера и фиксируется
//   из дашборда. Автоматики по заряду нет — выбирать зарядом
//   нечего с тех пор, как убран третий уровень «выживание»
//   (почему — в шапке power_calc.h). Заряд теперь трогает не
//   режим, а два рубежа ниже.
#define POWER_DEFAULT_MODE   POWER_ECO
//   Ночь — это только про экран: в экономе панель на это время
//   гасится, уровень остаётся прежним. Экрану разрешено гореть ровно в
//   оставшееся время — окно одно, второго набора часов нет намеренно.
#define POWER_NIGHT_ON_HOUR   22
#define POWER_NIGHT_OFF_HOUR   6
//   Ночью экран всё же можно зажечь из дашборда — но ненадолго: столько
//   он горит после команды, а дальше гаснет сам. Иначе забытый вечером
//   экран светил бы до утра, а это крупнейший потребитель.
#define POWER_SCREEN_PEEK_MS  30000UL
//   Заряда почти не осталось — гасим панель совсем, независимо от уровня,
//   расписания и подсветки: она самый крупный потребитель, и её отключение
//   заметно продлевает работу часов. Заодно снимает просадку, из-за которой
//   устройство уходило бы в brownout раньше времени. Этот рубеж не обходится
//   ничем: команда «включить экран» ниже него получает отказ, иначе полминуты
//   OLED роняли бы устройство совсем — вместо «показать время напоследок».
//
//   5 % — это ровно 3.70 В: ноль шкалы поднят до 3.65 ради ресурса банки
//   (battery_calc.h), и порог переехал вместе с ним, с прежних 3.60. Именно
//   этот рубеж и делает основную работу на исходе заряда: OLED тянет
//   150–180 мА на полной яркости против 20–30 у радио, так что снимать с
//   банки надо в первую очередь его.
//
#define POWER_SCREEN_OFF_PCT   5
//   Ноль шкалы — команда «стоп», а не просто ноль на индикаторе: на нём часы
//   уходят в deep sleep и перестают тянуть из банки вовсе (~20 мкА против
//   ~25 мА с погашенным экраном). Без этого поднятый до 3.65 В ноль защищал
//   элемент лишь наполовину: разряд продолжался до brownout на 3.55 В, просто
//   медленнее. Время в RTC сон переживает, так что часы просыпаются с верным
//   временем и без похода в сеть.
#define POWER_SLEEP_PCT        0
//   Проснуться насовсем — только когда заряд поднялся с запасом. Запас
//   обязателен: во сне нагрузки нет, банка отдыхает и напряжение само
//   подрастает на десятки милливольт. Без него часы вставали бы на этом
//   отскоке, тут же садились обратно и загружались по кругу каждые пять минут.
//   10 % по кривой — это 3.72 В, выше любого отскока, то есть достижимо
//   только настоящей зарядкой.
#define POWER_WAKE_PCT        10
//   Ноль должен продержаться столько, прежде чем усыплять. Одиночный выброс
//   АЦП не должен стоить пяти минут темноты.
#define POWER_SLEEP_CONFIRM_MS 30000UL
//   Как часто просыпаться и проверять заряд. Пробуждение короткое: читаем
//   АЦП и либо встаём совсем, либо спим дальше — ни экран, ни радио при этом
//   не поднимаются. Пять минут — компромисс между «воткнул USB и жду» и
//   расходом на сами проверки.
#define POWER_SLEEP_CHECK_MS  (5UL * 60UL * 1000UL)

