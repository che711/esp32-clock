#define POWER_WAKE_PCT        10
//   Ноль должен продержаться столько, прежде чем усыплять. Одиночный выброс
//   АЦП не должен стоить пяти минут темноты.
#define POWER_SLEEP_CONFIRM_MS 30000UL
//   Как часто просыпаться и проверять заряд. Пробуждение короткое: читаем
