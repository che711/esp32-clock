// Heartbeat WebSocket. Без него вкладка, пропавшая без закрытия соединения
// (закрыли крышку ноутбука, телефон ушёл из сети), так и числилась
// подключённой: снимок уходил ей раз в секунду в никуда, через несколько
// кадров забивался буфер отправки lwIP (TCP_SND_BUF, в IDF по умолчанию
// 4 × MSS ≈ 5.7 КБ — около семи снимков по ~830 байт), и дальше каждая
// рассылка вешала loop() на WEBSOCKETS_TCP_TIMEOUT — 5 с в библиотеке.
// Так продолжалось минуты, пока lwIP не бросал соединение по ретрансмитам.
//
// Отсюда требование: отключить такого клиента раньше, чем забьётся буфер.
// Худший случай — WS_PING_INTERVAL_MS + 2 × WS_PONG_TIMEOUT_MS = 5 с. Позже
// нельзя: при забитом буфере не уходит и сам ping, а пока ping не ушёл,
// библиотека пропуски не считает.
//
// Два ограничения самой библиотеки (links2004/WebSockets). Таймаут обязан быть
// короче интервала: каждый отправленный ping перезапускает отсчёт, и при
// обратном соотношении он не доходил бы до конца, пока не забьётся буфер. И
// пропусков нужно не меньше двух: соединение стартует с «pong не получен»,
