#pragma once
#include <stdint.h>
#include <stddef.h>

// ============================================================
//  battery_calc.h — пересчёт напряжения 18650 в проценты.
//
//  Без Arduino: собирается нативно и покрыто тестами.
//  Чтение АЦП и делителя — в battery.cpp.
// ============================================================

// Границы правдоподобия: вне их считаем, что АКБ не подключена — вход висит
// в воздухе, сработала защита по переразряду или делитель цепляет не банку.
//
// Верхняя граница с запасом над 4.2 В неспроста. Во-первых, TP4056 в фазе
// стабилизации напряжения держит на банке 4.2 В ±1 %. Во-вторых, BATTERY_CAL
// калибруется в середине разряда (3.7–3.8 В), где кривая круче всего, а
// множитель линейный: типичные 2–3 % поправки на верхнем конце превращают
// 4.20 В в 4.31–4.33. Граница вплотную к 4.35 отбрасывала именно полностью
// заряженную банку — то есть индикатор пропадал ровно тогда, когда заряд
// полный. Ошибиться в другую сторону тут нечем: питание мимо банки (5 В на
// делителе, вход перепутан) даёт после пересчёта 5 В и отсекается всё равно.
static const float BATTERY_PLAUSIBLE_MIN_V = 2.80f;
static const float BATTERY_PLAUSIBLE_MAX_V = 4.60f;

inline bool batteryVoltagePlausible(float v) {
    return v >= BATTERY_PLAUSIBLE_MIN_V && v <= BATTERY_PLAUSIBLE_MAX_V;
}

// Ноль шкалы — 3.50 В на банке. Это не «элемент пуст» (у Li-ion там ещё
// остаётся хвост до 3.0 В), а «пусто для этих часов»: между банкой и чипом
// стоят диод Шоттки (−0.3 В) и LDO платы (dropout 0.2–0.3 В), и ниже
// ~3.55 В на банке 3.3 В на выходе уже не удержать. Показывать проценты
// от ёмкости, до которой устройство не доживёт, — врать.
//
// Хвост при этом растянут, а не поджат, и это принципиально. Раньше между
// 3.74 В (20 %) и 3.72 В (10 %) умещалось десять процентов — 2 мВ на пункт,
// то есть меньше собственного шума АЦП: индикатор прыгал на 5–10 % на ровном
// месте, хотя банка стояла на месте. Теперь на тот же десяток процентов
// приходится 60 мВ, и шкала внизу движется, а не дрожит.
inline uint8_t batteryVoltageToPercent(float v) {
    // Кривая разряда Li-ion 18650 под малой нагрузкой (V → %)
    static const struct { float v; uint8_t pct; } CURVE[] = {
        {4.20f, 100}, {4.06f, 90}, {3.98f, 80}, {3.92f, 70},
        {3.87f, 60},  {3.82f, 50}, {3.79f, 40}, {3.77f, 30},
        {3.74f, 20},  {3.68f, 10}, {3.60f, 5},  {3.50f, 0},
    };
    static const size_t CURVE_N = sizeof(CURVE) / sizeof(CURVE[0]);

    if (v >= CURVE[0].v)           return 100;
    if (v <= CURVE[CURVE_N - 1].v) return 0;

    for (size_t i = 1; i < CURVE_N; i++) {
        if (v >= CURVE[i].v) {
            // Линейная интерполяция между точками i-1 и i
            float span = CURVE[i - 1].v - CURVE[i].v;
            float frac = (v - CURVE[i].v) / span;
            return (uint8_t)(CURVE[i].pct + frac * (CURVE[i - 1].pct - CURVE[i].pct));
        }
    }
    return 0;
}

// Проценты в миллиампер-часы. Это пересчёт, а не измерение: кулоновского
// счётчика в схеме нет, остаток по-прежнему выводится из напряжения. Единица
// при этом честнее процента отвечает на вопрос «надолго ли ещё»: при 25 мА
// в экономе 1300 мА·ч — это двое суток, и это видно сразу, а «50 %» нет.
inline uint16_t batteryRemainingMah(uint8_t pct, uint16_t usableMah) {
    if (pct > 100) pct = 100;
    return (uint16_t)(((uint32_t)pct * usableMah + 50) / 100);
}

// ── Фильтрация замеров ───────────────────────────────────
//  Wi-Fi потребляет импульсами: в момент передачи ток скачет со ~80
//  до ~300 мА, и напряжение на банке проваливается на десятки мВ.
//  Отсчёт, попавший в такой импульс, — выброс, а не измерение.
//  Среднее размазывает выброс по результату, медиана его отбрасывает.

// Медиана массива. Сортирует его на месте (вставками: n здесь ≤ 32).
inline uint32_t batteryMedianMv(uint32_t* v, size_t n) {
    if (n == 0) return 0;
    for (size_t i = 1; i < n; i++) {
        uint32_t key = v[i];
        size_t   j   = i;
        while (j > 0 && v[j - 1] > key) { v[j] = v[j - 1]; j--; }
        v[j] = key;
    }
    if (n & 1) return v[n / 2];
    return (v[n / 2 - 1] + v[n / 2]) / 2;
}

// Экспоненциальное сглаживание между наборами: alpha — вес свежего
// значения. Напряжение банки за доли секунды физически не меняется,
// поэтому быстрые движения — помеха, и давить их можно смело.
inline float batterySmooth(float prev, float fresh, float alpha) {
    return prev + alpha * (fresh - prev);
}

// Скачок больше порога — это не помеха, а событие: сняли USB, поменяли
// банку, сработала защита. Ползти к новому уровню полминуты незачем.
inline bool batteryJumped(float prev, float fresh, float threshold) {
    float d = fresh - prev;
    if (d < 0) d = -d;
    return d >= threshold;
}
