#pragma once
#include <stdint.h>
#include "power_calc.h"

// ============================================================
//  power.h — режимы энергосбережения.
//
//  Модуль хранит выбранный уровень и применяет к железу то, что
//  относится к нему самому: радио и яркость экрана. Сеть остаётся
//  за main.cpp — он владеет подключением.
//
//  Автоматики по заряду здесь больше нет. Она существовала ради
//  выживания (выбрать его на исходе банки и выпустить обратно при
//  зарядке); без выживания заряду нечего выбирать — оба уровня
//  держат радио живым. Заряд теперь трогает рубежи в config.h,
//  а не режим.
// ============================================================

void powerBegin();      // применить стартовый уровень, вызвать в setup()
void powerLoop();       // поправка на секундомер, вызывать из loop()

PowerMode   powerCurrent();       // что работает прямо сейчас
const char* powerModeName();
PowerMode   powerChosenMode();    // что выбрано пользователем

void powerSetMode(PowerMode m);   // выбрать уровень

// Рабочий уровень разошёлся с выбранным — сейчас это может значить только
// «идёт замер, держим обычный». Нужно дашборду: без пометки зафиксированный
// эконом с подсвеченным normal выглядит как не сработавшая кнопка, а не как
// «вернём со сбросом секундомера».
bool powerIsHeld();

// Параметры текущего профиля — их читает main.cpp
uint32_t powerSensorIntervalMs();
bool     powerLedEnabled();
// Два условия гашения экрана, и спрашиваются они всегда порознь. Расписание
// требует знать час, рубеж по заряду — нет, поэтому он работает и до первой
// синхронизации NTP. И перебить подсветкой можно только расписание: рубеж по
// заряду не обходится ничем (см. applyAutoBrightness/screenSetPower).
bool     powerScreenBatteryOkNow();       // false — заряд на исходе, панель гасим
bool     powerScreenScheduleAllowsNow(int hour);

// Радио сконфигурировать под текущий профиль. Вызывать после
// подключения: до него esp_wifi_* возвращают ошибку.
void powerApplyRadio();
